import { describe, expect, it } from "vitest";
import { catalogEntryId } from "../../src/core/catalog-entry-id.js";
import type { CatalogEntry } from "../../src/core/model.js";
import {
  reviewedContextualPreDrawReadingEligible,
  reviewedRoleAndOrdinalLineReadingEligible,
} from "../../src/readings/ordinal-line-context.js";
import type { RuntimeSyntaxProfile, Upos } from "../../src/syntax/types.js";

function word(text: string, reading: string): CatalogEntry {
  return {
    id: catalogEntryId(text, reading),
    prompt: { text, locale: "zh-TW" },
    syllables: [{ tokens: [] }],
    tags: ["reviewed-short-context"], provenanceIds: ["reviewed-short-context"],
  };
}
function role(entry: CatalogEntry, upos: Upos): RuntimeSyntaxProfile {
  return {
    id: entry.id + ":" + upos,
    entryId: entry.id, upos,
    functions: ["predicate"],
    valencyFrames: ["avalent"], provenanceIds: [],
    dependencyEvidence: { dependencyRelationCounts: {}, surfacePositionCounts: {} },
  };
}

type Case = {
  sentence: string;
  word: string;
  reading: string;
  upos: Upos;
  previousWord: string | null;
  expectedLegal: boolean;
};

/**
 * Illustrative, manually specified short sentences; explicitly assigned segmentation and
 * grammar roles. These examples are *not* independently attested corpus items, are not
 * generated by the product, and do *not* prove automatic syntax tagging,
 * downstream naturalness, or general G2P accuracy.
 *
 * Sources for the reviewed readings:
 * - 好: https://dict.concised.moe.edu.tw/dictView.jsp?ID=19419
 *       https://dict.concised.moe.edu.tw/dictView.jsp?ID=19462
 * - 行: https://dict.revised.moe.edu.tw/dictView.jsp?ID=4898&ver=4
 */
const known: readonly Case[] = [
  { sentence: "這家餐廳的服務很好。", word: "好", reading: "ㄏㄠ3",
    upos: "ADJ", previousWord: "很", expectedLegal: true },
  { sentence: "這家餐廳的服務很好。", word: "好", reading: "ㄏㄠ4",
    upos: "ADJ", previousWord: "很", expectedLegal: false },
  { sentence: "他愛好音樂。", word: "愛好", reading: "ㄞ4-ㄏㄠ4",
    upos: "VERB", previousWord: "他", expectedLegal: true },
  { sentence: "請看第三行。", word: "行", reading: "ㄏㄤ2",
    upos: "NOUN", previousWord: "第三", expectedLegal: true },
  { sentence: "請看第三行。", word: "行", reading: "ㄒㄧㄥ2",
    upos: "NOUN", previousWord: "第三", expectedLegal: false },
];

describe("manually reviewed natural short contexts (annotation-specific)", () => {
  for (const row of known) {
    it(`${row.sentence} / ${row.word} ${row.reading} => ${row.expectedLegal ? "licensed" : "rejected"}`, () => {
      const entry = word(row.word, row.reading);
      const profile = role(entry, row.upos);
      const previous = row.previousWord === null ? null : word(row.previousWord, "fixture");
      expect(reviewedRoleAndOrdinalLineReadingEligible(entry, profile, {}, previous))
        .toBe(row.expectedLegal);
      expect(reviewedContextualPreDrawReadingEligible(entry, profile, {}, previous))
        .toBe(row.expectedLegal);
    });
  }

  // The MOE Revised Dictionary explicitly documents 三行 meaning three
  // rows/lines and quotes a historical "三行字" context. Our predicate
  // currently only observes the *previous* lexeme and deliberately leaves
  // bare 三行 unconstrained because it has other attested senses. Supporting
  // "三行字" requires a reviewed following-word/semantic construction,
  // not a blanket 三+行 pronunciation shortcut.
  it.todo("請把這三行字抄下來：needs following-word evidence for 行/ㄏㄤ2");
});
